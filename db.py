"""PostgreSQL schema and connection helpers."""
import os
from contextlib import contextmanager

import psycopg
from dotenv import load_dotenv

# Every write transaction takes this lock first, so writers take turns and
# check-then-insert logic ("is this group full?") can't race.
WRITE_LOCK = 107_001

SCHEMA = """
CREATE TABLE IF NOT EXISTS courses (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  subject TEXT NOT NULL,
  number TEXT NOT NULL,
  title TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  units TEXT,
  department TEXT NOT NULL,
  school TEXT NOT NULL,
  source_url TEXT NOT NULL,
  active INTEGER NOT NULL DEFAULT 1,
  UNIQUE (subject, number)
);
CREATE TABLE IF NOT EXISTS majors (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE,
  school TEXT NOT NULL,
  source_url TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS major_courses (
  major_id INTEGER NOT NULL REFERENCES majors(id) ON DELETE CASCADE,
  course_id INTEGER NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
  PRIMARY KEY (major_id, course_id)
);
CREATE TABLE IF NOT EXISTS catalog_meta (key TEXT PRIMARY KEY, value TEXT NOT NULL);

CREATE TABLE IF NOT EXISTS users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email TEXT NOT NULL,
  name TEXT NOT NULL,
  password_hash TEXT NOT NULL,
  role TEXT NOT NULL CHECK (role IN ('student', 'tutor')),
  major_id INTEGER REFERENCES majors(id) ON DELETE SET NULL,
  bio TEXT NOT NULL DEFAULT '',
  student_enabled INTEGER NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL DEFAULT (to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'))
);
-- Emails are unique ignoring case.
CREATE UNIQUE INDEX IF NOT EXISTS idx_users_email ON users (lower(email));
CREATE TABLE IF NOT EXISTS sessions (
  token_hash TEXT PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires_at DOUBLE PRECISION NOT NULL,
  active_role TEXT CHECK (active_role IN ('student', 'tutor'))
);

CREATE TABLE IF NOT EXISTS tutor_courses (
  tutor_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  course_id INTEGER NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
  PRIMARY KEY (tutor_id, course_id)
);
CREATE TABLE IF NOT EXISTS tutor_slots (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tutor_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  starts_at TEXT NOT NULL,
  ends_at TEXT NOT NULL,
  location TEXT NOT NULL,
  cancelled_at TEXT
);
CREATE INDEX IF NOT EXISTS idx_slots_tutor ON tutor_slots (tutor_id, starts_at);
CREATE TABLE IF NOT EXISTS bookings (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slot_id INTEGER NOT NULL UNIQUE REFERENCES tutor_slots(id) ON DELETE CASCADE,
  student_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  course_id INTEGER NOT NULL REFERENCES courses(id),
  note TEXT NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS idx_bookings_student ON bookings (student_id);

CREATE TABLE IF NOT EXISTS study_groups (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course_id INTEGER NOT NULL REFERENCES courses(id),
  creator_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  topic TEXT NOT NULL,
  starts_at TEXT NOT NULL,
  ends_at TEXT NOT NULL,
  location TEXT NOT NULL,
  capacity INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_groups_course ON study_groups (course_id, starts_at);
CREATE TABLE IF NOT EXISTS study_group_members (
  group_id INTEGER NOT NULL REFERENCES study_groups(id) ON DELETE CASCADE,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  PRIMARY KEY (group_id, user_id)
);
CREATE INDEX IF NOT EXISTS idx_members_user ON study_group_members (user_id);
"""

# Tables in an order where each one's references come before it.
TABLES = [
    "courses", "majors", "major_courses", "catalog_meta", "users", "sessions",
    "tutor_courses", "tutor_slots", "bookings", "study_groups", "study_group_members",
]

# Columns added after the first release, so databases that already exist pick them up.
ADDED_COLUMNS = {
    "users": {"student_enabled": "INTEGER NOT NULL DEFAULT 0"},
    "sessions": {"active_role": "TEXT CHECK (active_role IN ('student', 'tutor'))"},
    # The names of shared files; the files themselves are in Cloud Storage. A tutoring session can
    # have the tutor's file (on the time slot) and the student's file (on the booking).
    "tutor_slots": {"attachment_name": "TEXT"},
    "bookings": {"attachment_name": "TEXT"},
    "study_groups": {"attachment_name": "TEXT"},
}


def database_url():
    """The DATABASE_URL setting, read from the environment or a local .env file."""
    load_dotenv()
    url = os.environ.get("DATABASE_URL", "").strip()
    if not url:
        raise SystemExit(
            "DATABASE_URL is not set.\n"
            "Add it to the .env file in the project folder (on a laptop) or to the server's environment, e.g.\n"
            "  DATABASE_URL=postgresql://USER:PASSWORD@HOST/DBNAME?sslmode=require"
        )
    return url


class Row(dict):
    """A result row readable by column name, like a dict, or by position: row[0]."""

    def __getitem__(self, key):
        if isinstance(key, int):
            return list(self.values())[key]
        return super().__getitem__(key)


def _row_factory(cursor):
    names = [column.name for column in cursor.description or []]
    return lambda values: Row(zip(names, values))


def connect(url):
    """Opens a connection in autocommit mode; multi-statement writes use transaction().

    Prepared statements are off because Neon's connection pooler hands each
    transaction to whichever server connection is free.
    """
    return psycopg.connect(url, autocommit=True, row_factory=_row_factory, prepare_threshold=None)


def init_database(url):
    """Creates any missing tables. Safe to run at every start, from several processes at once."""
    with connect(url) as db, db.transaction():
        db.execute("SELECT pg_advisory_xact_lock(%s)", (WRITE_LOCK,))
        db.execute(SCHEMA)
        for table, columns in ADDED_COLUMNS.items():
            for name, definition in columns.items():
                db.execute(f"ALTER TABLE {table} ADD COLUMN IF NOT EXISTS {name} {definition}")


@contextmanager
def transaction(db):
    """Runs a block atomically, one writer at a time.

    Concurrent writers take turns on a shared lock, so check-then-insert logic
    (like "is this group full?") can't race between requests. The lock is
    released when the transaction ends.
    """
    with db.transaction():
        db.execute("SELECT pg_advisory_xact_lock(%s)", (WRITE_LOCK,))
        yield
